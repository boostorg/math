template <class Real>
void evaluate(const reference& r, Real* f, Real* fp)
{
   const Real c = static_cast<Real>(r.c);
   const Real x = static_cast<Real>(r.x);
   switch (r.what)
   {
   case quantity::angular:
      *f = r.oblate ? oblate_spheroidal_angular(r.n, r.m, c, x, fp) : prolate_spheroidal_angular(r.n, r.m, c, x, fp);
      break;
   case quantity::radial_1:
      *f = r.oblate ? oblate_spheroidal_radial_1(r.n, r.m, c, x, fp) : prolate_spheroidal_radial_1(r.n, r.m, c, x, fp);
      break;
   case quantity::radial_2:
      *f = r.oblate ? oblate_spheroidal_radial_2(r.n, r.m, c, x, fp) : prolate_spheroidal_radial_2(r.n, r.m, c, x, fp);
      break;
   }
}

// Errors are measured against the local envelope max(|f|, |x f'|, |f'|/k), k = max(c, 1) for the
// radial and n + c + 1 for the angular functions: near a zero of an oscillating function the relative
// error is meaningless, and one ulp of x already moves the value by about |x f'| ε.
// The methods lose accuracy roughly in proportion to c (more integration steps, more cancellation).
template <class Real>
void test_references()
{
   using std::abs;
   using std::max;
   const Real eps = std::numeric_limits<Real>::epsilon();
   for (const reference& r : references)
   {
      // The references are at the double arguments; rounding them to Real costs about |f'| |Δx|,
      // and can land a prolate radial argument on the singular point ξ = 1.
      const double dx = abs(static_cast<double>(static_cast<Real>(r.x)) - r.x);
      if (r.what != quantity::angular && !r.oblate && static_cast<Real>(r.x) <= 1)
      {
         continue;
      }
      Real f;
      Real fp;
      evaluate(r, &f, &fp);
      const double k = r.what == quantity::angular ? r.n + r.c + 1 : max(r.c, 1.0);
      const double x = r.what == quantity::angular ? 0.0 : r.x;
      const double scale = max({ abs(r.f), abs(x * r.fp), abs(r.fp) / k });
      const double dscale = max({ abs(r.fp), abs(x * r.fpp), abs(r.fpp) / k, r.what == quantity::angular ? abs(r.f) * k : 0.0 });
      const Real tol = 64 * (1 + static_cast<Real>(r.c)) * eps;
      CHECK_ABSOLUTE_ERROR(static_cast<Real>(r.f), f, tol * static_cast<Real>(scale) + static_cast<Real>(2 * abs(r.fp) * dx));
      CHECK_ABSOLUTE_ERROR(static_cast<Real>(r.fp), fp, tol * static_cast<Real>(dscale) + static_cast<Real>(2 * abs(r.fpp) * dx));
   }
   for (const eigen_reference& e : eigenvalues)
   {
      const Real c = static_cast<Real>(e.c);
      const Real lambda = e.oblate ? oblate_spheroidal_eigenvalue(e.n, e.m, c) : prolate_spheroidal_eigenvalue(e.n, e.m, c);
      const double scale = max({ abs(e.lambda), e.c * e.c, double(e.n * (e.n + 1)) });
      CHECK_ABSOLUTE_ERROR(static_cast<Real>(e.lambda), lambda, 32 * eps * static_cast<Real>(scale));
   }
}

template <class Real>
void test_identities()
{
   using std::abs;
   const Real eps = std::numeric_limits<Real>::epsilon();
   // A closed form (Mathematica): R^(1)_11(π/2, 3/2) = 2 sqrt(2/5)/π.
   CHECK_RELATIVE_ERROR(Real(0.40263369683589628028982024114197150961L),
                        prolate_spheroidal_radial_1(1u, 1u, boost::math::constants::half_pi<Real>(), Real(1.5)), 8 * eps);
   // More generally, for m = 1 and γ = nπ/2 the eigenvalue is 0 and R^(1) = sin(γ(x - 1))/(γ sqrt(x² - 1)).
   for (unsigned n = 1; n <= 8; ++n)
   {
      const Real g = n * boost::math::constants::half_pi<Real>();
      CHECK_ABSOLUTE_ERROR(Real(0), prolate_spheroidal_eigenvalue(n, 1u, g), 8 * eps * (n * (n + 1) + g * g));
      for (Real x : { Real(1.2), Real(1.5), Real(2.3), Real(3.7), Real(7.25) })
      {
         const Real amplitude = 1 / (g * sqrt(x * x - 1));
         CHECK_ABSOLUTE_ERROR(sin(g * (x - 1)) * amplitude, prolate_spheroidal_radial_1(n, 1u, g, x), 8 * eps * (1 + g * x) * amplitude);
      }
   }
   // c = 0 reduces the angular function to the Ferrers function (with the Condon-Shortley phase),
   // and both families agree there.
   for (unsigned m = 0; m < 4; ++m)
   {
      for (unsigned n = m; n < m + 6; ++n)
      {
         const Real x = Real(3) / 10;
         const Real P = boost::math::legendre_p(static_cast<int>(n), static_cast<int>(m), x);
         CHECK_ULP_CLOSE(P, prolate_spheroidal_angular(n, m, Real(0), x), 64);
         CHECK_ULP_CLOSE(P, oblate_spheroidal_angular(n, m, Real(0), x), 64);
      }
   }
   // λ_n^m(0) = n(n + 1) for both families.
   for (unsigned n = 0; n <= 200; ++n)
   {
      for (unsigned m = 0; m <= n; m += 1 + n / 8)
      {
         if (n == 0)
         {
            CHECK_ABSOLUTE_ERROR(Real(0), prolate_spheroidal_eigenvalue(n, m, Real(0)), eps);
            CHECK_ABSOLUTE_ERROR(Real(0), oblate_spheroidal_eigenvalue(n, m, Real(0)), eps);
            continue;
         }
         CHECK_ULP_CLOSE(Real(n * (n + 1)), prolate_spheroidal_eigenvalue(n, m, Real(0)), 2);
         CHECK_ULP_CLOSE(Real(n * (n + 1)), oblate_spheroidal_eigenvalue(n, m, Real(0)), 2);
      }
   }
   // Parity: Ps(-η) = (-1)^{n-m} Ps(η).
   for (unsigned n = 2; n < 6; ++n)
   {
      const Real s = (n - 2) % 2 ? Real(-1) : Real(1);
      CHECK_ULP_CLOSE(s * prolate_spheroidal_angular(n, 2u, Real(5), Real(0.6)), prolate_spheroidal_angular(n, 2u, Real(5), Real(-0.6)), 4);
      CHECK_ULP_CLOSE(s * oblate_spheroidal_angular(n, 2u, Real(30), Real(0.2)), oblate_spheroidal_angular(n, 2u, Real(30), Real(-0.2)), 4);
   }
   // Wronskians R1 R2' - R1' R2 = 1/(c(ξ² - 1)) (prolate) and 1/(c(ξ² + 1)) (oblate) over a wider range.
   // Near ξ = 1 the error in R2 grows like ε/(ξ - 1), in line with its condition number.
   for (Real c : { Real(0.25), Real(3), Real(30), Real(100) })
   {
      for (unsigned n : { 0u, 1u, 4u, 9u })
      {
         for (unsigned m : { 0u, 1u, 3u })
         {
            if (m > n)
            {
               continue;
            }
            for (Real xi : { Real(1.0001), Real(1.01), Real(1.1), Real(2), Real(10) })
            {
               Real R1d;
               Real R2d;
               const Real R2 = prolate_spheroidal_radial_2(n, m, c, xi, &R2d);
               const Real W = prolate_spheroidal_radial_1(n, m, c, xi, &R1d) * R2d - R1d * R2;
               CHECK_RELATIVE_ERROR(1 / (c * (xi - 1) * (xi + 1)), W, 64 * (1 + c) * (1 + Real(0.01) / (xi - 1)) * eps);
            }
            for (Real xi : { Real(0), Real(0.1), Real(1), Real(10) })
            {
               Real R1d;
               Real R2d;
               const Real R2 = oblate_spheroidal_radial_2(n, m, c, xi, &R2d);
               const Real W = oblate_spheroidal_radial_1(n, m, c, xi, &R1d) * R2d - R1d * R2;
               CHECK_RELATIVE_ERROR(1 / (c * (xi * xi + 1)), W, 64 * (1 + c) * eps);
            }
         }
      }
   }
   // At ξ = 1, R1 vanishes for m > 0 and R2 is infinite.
   CHECK_EQUAL(prolate_spheroidal_radial_1(3u, 1u, Real(2), Real(1)), Real(0));
   Real d;
   prolate_spheroidal_radial_1(4u, 3u, Real(2), Real(1), &d);
   CHECK_EQUAL(d, Real(0));
   CHECK_ULP_CLOSE(prolate_spheroidal_radial_1(2u, 0u, Real(2), Real(1) + eps), prolate_spheroidal_radial_1(2u, 0u, Real(2), Real(1)), 16);
   // Ps vanishes at η = ±1 for m > 0 (its derivative is infinite for m = 1).
   CHECK_EQUAL(abs(prolate_spheroidal_angular(2u, 1u, Real(2), Real(1))), Real(0));
   CHECK_EQUAL(abs(oblate_spheroidal_angular(1u, 1u, Real(2), Real(-1))), Real(0));
   // At η = 1 the Legendre series cancels completely for prolate functions with large c (Arb reference).
   CHECK_RELATIVE_ERROR(Real(1.3561360049409084e-20), prolate_spheroidal_angular(0u, 0u, Real(50), Real(1)), 64 * 51 * eps);
   CHECK_RELATIVE_ERROR(Real(1.3561360049409084e-20), prolate_spheroidal_angular(0u, 0u, Real(50), Real(-1)), 64 * 51 * eps);
   // Tiny oblate arguments reach the ξ = 0 limit.
   CHECK_ULP_CLOSE(oblate_spheroidal_radial_1(2u, 2u, Real(1), Real(0)), oblate_spheroidal_radial_1(2u, 2u, Real(1), std::numeric_limits<Real>::min()), 2);
   Real d0;
   oblate_spheroidal_radial_1(1u, 0u, Real(1), Real(0), &d0);
   oblate_spheroidal_radial_1(1u, 0u, Real(1), std::numeric_limits<Real>::min(), &d);
   CHECK_ULP_CLOSE(d0, d, 2);
#ifndef BOOST_MATH_NO_EXCEPTIONS
   CHECK_THROW(prolate_spheroidal_angular(2u, 1u, Real(2), Real(1), &d), std::overflow_error);
   CHECK_THROW(prolate_spheroidal_radial_2(0u, 0u, Real(2), Real(1)), std::overflow_error);
   CHECK_THROW(prolate_spheroidal_radial_1(1u, 1u, Real(2), Real(1), &d), std::overflow_error);
#endif
}

// Negative c: everything is even in c except R^(1) and R^(2), which change by (-1)^n and (-1)^(n+1).
