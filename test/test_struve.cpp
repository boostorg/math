// f'' from the differential equations DLMF 11.2.7 and 11.2.9, for the condition number of f'.
double second_derivative(bool modified, const reference& r)
{
   const double b = r.nu + 0.5;
   int sign = 1;
   const double lg = (b <= 0 && std::floor(b) == b) ? std::numeric_limits<double>::infinity() : boost::math::lgamma(b, &sign);
   const double rhs = sign * 4 * std::exp((r.nu + 1) * std::log(r.x / 2) - lg) / boost::math::constants::root_pi<double>();
   const double x2 = r.x * r.x;
   return (rhs - r.x * r.fp - (modified ? -(x2 + r.nu * r.nu) : x2 - r.nu * r.nu) * r.f) / x2;
}

// Errors are measured against the condition number |x f'/f| of each value (see check_conditioned_error).
template <class Real>
void test_references()
{
   for (int modified = 0; modified < 2; ++modified)
   {
      const reference* begin = modified ? l_references : h_references;
      const std::size_t n = modified ? sizeof(l_references) / sizeof(reference) : sizeof(h_references) / sizeof(reference);
      for (const reference* r_ = begin; r_ != begin + n; ++r_)
      {
         const reference& r = *r_;
         if (std::fabs(r.f) > (std::numeric_limits<Real>::max)() / 4 || std::fabs(r.fp) > (std::numeric_limits<Real>::max)() / 4)
         {
            continue;
         }
         const Real nu = static_cast<Real>(r.nu);
         const Real x = static_cast<Real>(r.x);
         if (static_cast<double>(nu) != r.nu || static_cast<double>(x) != r.x)
         {
            continue;
         }
         Real d;
         const Real f = modified ? struve_l(nu, x, &d) : struve_h(nu, x, &d);
         // Rows with |nu| > 100 are regression tests for overflow and NaN outside the documented range, where
         // the error grows with |nu| and varies between platforms.
         const Real k = std::fabs(r.nu) > 100 ? Real(16) : Real(1);
         CHECK_CONDITIONED_ERROR(x, r.f, r.fp, f, 4 * k);
         CHECK_CONDITIONED_ERROR(x, r.fp, second_derivative(modified != 0, r), d, 16 * k);
         CHECK_EQUAL(f, modified ? struve_l(nu, x) : struve_h(nu, x));
      }
   }
}

template <class Real>
void test_identities()
{
   using std::sqrt;
   using std::sin;
   using std::cos;
   using std::sinh;
   using std::cosh;
   const Real eps = std::numeric_limits<Real>::epsilon();
   const Real pi = boost::math::constants::pi<Real>();
   const Real half = Real(1) / 2;
   for (Real x : { Real(0.125), Real(1), Real(2.5), Real(9), Real(30) })
   {
      const Real s = sqrt(2 / (pi * x));
      // Half-integer orders, DLMF 11.4.5 and 11.4.7: H_{1/2} = s (1 - cos x), L_{1/2} = s (cosh x - 1).
      // 1 - cos x is written as 2 sin^2(x/2).
      const Real sh = sin(x / 2);
      CHECK_RELATIVE_ERROR(2 * s * sh * sh, struve_h(half, x), 8 * eps);
      const Real shh = sinh(x / 2);
      CHECK_RELATIVE_ERROR(2 * s * shh * shh, struve_l(half, x), 8 * eps);
      // DLMF 11.4.4: H_{-(n+1/2)} = (-1)^n J_{n+1/2} and L_{-(n+1/2)} = I_{n+1/2}.
      for (unsigned n = 0; n <= 8; ++n)
      {
         const Real nu = n + half;
         CHECK_RELATIVE_ERROR((n % 2 ? -1 : 1) * boost::math::cyl_bessel_j(nu, x), struve_h(-nu, x), 8 * eps);
         CHECK_RELATIVE_ERROR(boost::math::cyl_bessel_i(nu, x), struve_l(-nu, x), 8 * eps);
      }
      // MathWorld's closed forms for H_{3/2} and H_{5/2}; they cancel below x ≈ 2.
      if (x > 2)
      {
         const Real r = sqrt(2 * pi);
         const Real x2 = x * x;
         CHECK_RELATIVE_ERROR((2 + x2 - 2 * cos(x) - 2 * x * sin(x)) / (r * x * sqrt(x)), struve_h(3 * half, x), 8 * eps);
         CHECK_RELATIVE_ERROR((24 + 4 * x2 + x2 * x2 + 8 * (x2 - 3) * cos(x) - 24 * x * sin(x)) / (4 * r * x2 * sqrt(x)),
                              struve_h(5 * half, x), 8 * eps);
      }
      // Reflection for integer orders, DLMF 11.4.16 and 11.4.17.
      for (int n = -3; n <= 4; ++n)
      {
         Real d1;
         Real d2;
         const Real sign = (n % 2 == 0) ? Real(-1) : Real(1);
         CHECK_EQUAL(sign * struve_h(Real(n), x, &d1), struve_h(Real(n), Real(-x), &d2));
         CHECK_EQUAL(-sign * d1, d2);
         CHECK_EQUAL(sign * struve_l(Real(n), x, &d1), struve_l(Real(n), Real(-x), &d2));
         CHECK_EQUAL(-sign * d1, d2);
      }
   }
   // Recurrences DLMF 11.4.23 and 11.4.25, and H' = H_{nu-1} - (nu/x) H_nu, at points where they do not cancel.
   for (Real nu : { Real(0.25), Real(2.75), Real(7) })
   {
      for (Real x : { Real(0.5), Real(4), Real(20) })
      {
         const Real t = std::pow(x / 2, nu) / (sqrt(pi) * std::tgamma(nu + Real(1.5)));
         const Real hm = struve_h(nu - 1, x);
         const Real h = struve_h(nu, x);
         const Real hp = struve_h(nu + 1, x);
         CHECK_ABSOLUTE_ERROR(2 * nu / x * h + t, hm + hp, 64 * eps * (std::fabs(hm) + std::fabs(hp) + std::fabs(t)));
         Real d;
         struve_h(nu, x, &d);
         CHECK_ABSOLUTE_ERROR(hm - nu / x * h, d, 64 * eps * (std::fabs(hm) + std::fabs(nu / x * h)));
         const Real lm = struve_l(nu - 1, x);
         const Real l = struve_l(nu, x);
         const Real lp = struve_l(nu + 1, x);
         CHECK_ABSOLUTE_ERROR(2 * nu / x * l + t, lm - lp, 64 * eps * (std::fabs(lm) + std::fabs(lp) + std::fabs(t)));
         struve_l(nu, x, &d);
         CHECK_ABSOLUTE_ERROR(lm - nu / x * l, d, 64 * eps * (std::fabs(lm) + std::fabs(nu / x * l)));
      }
   }
}

template <class Real>
void test_special_values()
{
   const Real two_div_pi = boost::math::constants::two_div_pi<Real>();
   Real d;
   CHECK_EQUAL(Real(0), struve_h(Real(0), Real(0), &d));
   CHECK_EQUAL(two_div_pi, d);
   CHECK_EQUAL(Real(0), struve_l(Real(0), Real(0), &d));
   CHECK_EQUAL(two_div_pi, d);
   CHECK_EQUAL(Real(0), struve_h(Real(3.5), Real(0), &d));
   CHECK_EQUAL(Real(0), d);
   CHECK_EQUAL(two_div_pi, struve_h(Real(-1), Real(0), &d));
   CHECK_EQUAL(Real(0), d);
   CHECK_EQUAL(two_div_pi, struve_l(Real(-1), Real(0)));
   CHECK_EQUAL(Real(0), struve_h(Real(-2.5), Real(0), &d));
   CHECK_EQUAL(Real(0), d);
   CHECK_EQUAL(Real(0), struve_h(Real(-0.5), Real(0)));
#ifndef BOOST_MATH_NO_EXCEPTIONS
   CHECK_THROW(struve_h(Real(0.5), Real(-1)), std::domain_error);
   CHECK_THROW(struve_l(Real(-2.25), Real(-1)), std::domain_error);
   CHECK_THROW(struve_h(std::numeric_limits<Real>::quiet_NaN(), Real(1)), std::domain_error);
   CHECK_THROW(struve_l(Real(1), std::numeric_limits<Real>::infinity()), std::domain_error);
   CHECK_THROW(struve_h(Real(-1.25), Real(0)), std::overflow_error);
   CHECK_THROW(struve_l(Real(-3), Real(0)), std::overflow_error);
   CHECK_THROW(struve_h(Real(-0.5), Real(0), &d), std::overflow_error);
   CHECK_THROW(struve_l(Real(0), Real(800)), std::overflow_error);
   CHECK_THROW(struve_h(Real(-332.25), Real(12)), std::overflow_error);
#endif
}

